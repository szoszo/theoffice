def detect_once(d):
    now = d["now"](); st = load_state(d["state_path"])
    hint = ""; forced = os.path.exists(d["force_path"]) and open(d["force_path"]).read().strip() == "outage"; need = 2
    if forced: bad, reason = True, "forced drill"
    else:
        h_ok, h_why = d["health"](); n, hint = d["panes"](); s_bad, s_why = d["status"](); q_bad, q_why = d["quota"]() if d.get("quota") else (False, "")
        hard = (not h_ok) or n >= 2 or q_bad   # the limit is account-wide: two panes on the modal is hard evidence; one pane is a hint; the status page ALONE never counts (a status "partial outage" with the primary agent answering once ran a takeover for hours)
        dead = d["dead"](True) if (s_bad or n == 1) and not hard else False
        bad = hard or n == 1 or (s_bad and dead)
        reason = (f"usage limit, {hint}" if hint else "usage limit") if n > 0 else ((h_why if not h_ok else "") or (q_why if q_bad else "") or s_why)
        need = 2 if hard else (2 if (bad and dead) else 3)   # one pane: three checks, or two when the primary agent is also silent; the status page counts only together with a silent primary
    st, tr = decide(st, bad, reason, now, need)
    if tr == "outage": st["outage_since"] = now; st["reset"] = hint; st["todo"] = {"act": "start", "tell": f":rotating_light: Claude is out ({st['reason']}). {C()['captain_name']} is emergency captain."}
    elif tr == "recovered":
        st, back = revert_all(st, now, d.get("agents_dir", AGENTS_DIR)); st["to_restart"] = back
        st["todo"] = {"act": "end", "tell": f"Claude is back. {C()['primary_name']} has the con again." + (f" Back on Claude: {', '.join(back)}." if back else "")}
    save_state(st, d["state_path"]); todo = st.get("todo") or {}   # the start step reads reason / since / reset from the saved state
    if todo.get("act") and d[todo["act"]]() is not False: todo["act"] = None            # a failed start/end is retried on the next tick, not lost
    if todo.get("tell") and d["owner"](todo["tell"]) is not False: todo["tell"] = None  # the owner line is sent exactly once, retried until the channel takes it
    st["todo"] = todo if (todo.get("act") or todo.get("tell")) else {}
    # ONE usage line when the captain takes over, never hourly.
    if tr == "outage" and d.get("usage"):
        try: text = d["usage"]()
        except Exception: text = None
        if text: d["owner"](text)
    save_state(st, d["state_path"]); return st, tr

SKIP_MARK = 'skipped (captain outage skip list)'
DUP_MARK = "skipped (captain: the captain already has this task)"
def _move_to_captain(c, rid, frm, prompt, channel=None):
    """Re-address one queued row to the captain. If the captain already holds a row with the same (agent, dedup_key) the move would violate the unique index: that one row is marked skipped and the pass goes on (one poisoned row must not abort every pass)."""
    cap = CAP()
    try:
        if channel is None: cur = c.execute("UPDATE inbound_queue SET agent_id=?, prompt=? WHERE id=? AND status='queued' AND agent_id=?", (cap, prompt, rid, frm))
        else: cur = c.execute("UPDATE inbound_queue SET agent_id=?, prompt=?, reply_channel=CASE WHEN source='channel' THEN ? ELSE reply_channel END WHERE id=? AND status='queued' AND agent_id=?", (cap, prompt, channel, rid, frm))
        return cur.rowcount
    except sqlite3.IntegrityError:
        c.execute("UPDATE inbound_queue SET status='failed', last_error=? WHERE id=? AND status='queued'", (DUP_MARK, rid)); return 0
def route_once(db, state_path, owner_user, now=None):
    """During an OUTAGE re-address the owner's DMs and the primary agent's scheduled tasks to the captain. Bus mail for the primary agent stays queued for it. Idempotent.
    The owner's text comes FIRST and the captain note after it (with the note first, a real ask was once read as the announcement). An owner DM that the engine already DELIVERED to the primary agent's dead pane during this outage (it does that within 2 s, the router polls every 1 s) is put back on the captain's queue."""
    st0 = load_state(state_path)
    if st0["state"] != "outage": return 0
    if primary_alive(db, now): return 0   # the primary agent answered in the last 5 minutes: routing its DMs too would make two agents answer the owner
    p, cap = P(), CAP()
    post = (f"\n\n---\n{MARK} (Claude is out, you act for {C()['primary_name']} with its hard rules; read the CAPTAIN MODE section of your AGENTS.md). "
            f":rotating_light: Start every message to the owner with 'Emergency captain ({C()['captain_name']}):'. The text ABOVE the line is the original message.")
    any_mark = "%" + MARK + "%"
    since = st0.get("outage_since") or st0.get("since") or 0
    c = sqlite3.connect(db, timeout=10); n = 0
    try:
        for t in C()["skip_tasks"]: c.execute("UPDATE inbound_queue SET status='failed', last_error=? WHERE status='queued' AND source='scheduler' AND dedup_key LIKE ?", (SKIP_MARK, f"sched:{t}:%"))
        for r in c.execute("SELECT id, source, prompt FROM inbound_queue WHERE status='queued' AND agent_id=? AND prompt NOT LIKE ? AND ((source='channel' AND reply_user=? AND reply_channel LIKE 'D%') OR source IN ('scheduler','manual'))", (p, any_mark, owner_user)).fetchall():
            n += _move_to_captain(c, r[0], p, r[2] + post, owner_user)
        if since > 0:   # no known outage start: never sweep history
            for r in c.execute("SELECT id, prompt, reply_channel, created_at FROM inbound_queue WHERE status='delivered' AND agent_id=? AND source='channel' AND reply_user=? AND reply_channel LIKE 'D%' AND created_at>=? AND prompt NOT LIKE ?", (p, owner_user, since, any_mark)).fetchall():
                try: answered = c.execute("SELECT 1 FROM outbound_queue WHERE agent_id=? AND channel=? AND created_at>=? LIMIT 1", (p, r[2], r[3])).fetchone()
                except sqlite3.OperationalError: answered = None
                if answered: continue   # the primary agent already replied in that DM: a second answer from the captain would be a duplicate
                try: n += c.execute("UPDATE inbound_queue SET agent_id=?, status='queued', delivered_at=NULL, prompt=?, reply_channel=?, attempts=0, requeues=0, owner_alarmed_at=NULL, session_ref=NULL, last_error=NULL WHERE id=? AND status='delivered' AND agent_id=?", (cap, r[1] + post, owner_user, r[0], p)).rowcount
                except sqlite3.IntegrityError: pass
        # the other agents' scheduled and manual tasks fire into dead panes too: the captain takes them, labelled FOR <agent>; an agent the captain switched to Codex keeps its own
        switched = {x["agent"] for x in active_switches(st0)}
        for a in C()["covered_agents"]:
            if a in switched: continue
            tag = f"[FOR {a}, read their CLAUDE.md first] "
            for r in c.execute("SELECT id, prompt FROM inbound_queue WHERE status='queued' AND agent_id=? AND source IN ('scheduler','manual') AND prompt NOT LIKE '[FOR %'", (a,)).fetchall():
                n += _move_to_captain(c, r[0], a, tag + r[1] + post)
        c.commit()
    finally: c.close()
    return n

def primary_alive(db, now=None, window=300):
    """The primary agent sent something to the owner (outbound queue) within `window` seconds. DB only; a missing table or an error counts as not alive."""
    now = time.time() if now is None else now
    try:
        c = sqlite3.connect(db, timeout=10)
        try: r = c.execute("SELECT created_at FROM outbound_queue WHERE agent_id=? ORDER BY id DESC LIMIT 1", (P(),)).fetchone()
        finally: c.close()
    except Exception: return False
    if not r or not r[0]: return False
    t = r[0] / 1000 if r[0] > 1e12 else r[0]
    return now - t < window
def ensure_handoff(path, outage_start, log_path, now=None):
    """At recovery: if the captain's handoff file is missing or older than the outage start, write a stub marked as auto-generated. The captain's own fresh file is never overwritten. True when a stub was written."""
    now = time.time() if now is None else now
    try:
        if os.path.getmtime(path) >= (outage_start or 0): return False
    except OSError: pass
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w").write(f"# Captain handoff (auto-generated by the captain code, NOT written by {C()['captain_name']})\nGenerated: {datetime.datetime.fromtimestamp(now, tz()).isoformat()}\n\n"
                          f"{C()['captain_name']} did not refresh this file during the outage. The exact record of the outage is the captain log: {log_path}\nWhat was open is in that log (inbound, outbound, bus, drafts, switches).\n")
    return True

def section(md, head):
    m = re.search(rf"^(#{{2,3}}) {re.escape(head)}.*?$", md, re.M)
    if not m: return ""
    lvl = len(m.group(1)); rest = md[m.end():]; e = re.search(rf"^#{{2,{lvl}}} ", rest, re.M)
    return (m.group(0) + rest[: e.start() if e else len(rest)]).strip()

def briefing_hm(path=None):
    """(hour, minute) of today's briefing from its task cron (a task may rewrite it every morning), None if unconfigured, unreadable or not a daily 'M H * * *' cron."""
    path = path or C()["briefing_task"]
    if not path: return None
    try: m = re.fullmatch(r"(\d{1,2}) (\d{1,2}) \* \* \*", json.load(open(cfg.resolve(path))).get("schedule", "").strip())
    except Exception: return None
    return (int(m.group(2)), int(m.group(1))) if m else None
def priority_now(now, hm):
    """The configured priority text with the briefing item made time-aware: before its time it names the time, after it it is only a check that it went out."""
    pr = C()["priority"]; item = C()["briefing_item"]
    if not hm or not item or item not in pr: return pr
    t = datetime.datetime.fromtimestamp(now, tz())
    now_item = f"{item} at {hm[0]:02d}:{hm[1]:02d}" if (t.hour, t.minute) < hm else "today's briefing only if it did not go out (check the owner DM first)"
    return pr.replace(item, now_item)
def announcement(st, gaps=None, now=None, briefing_hm=None):
    """The captain's first message in its own DM on every switch. Built from the configured priority, the gap list and the live state, so it cannot drift from the rules block."""
    if briefing_hm is None and now is None: briefing_hm = globals()["briefing_hm"](); now = time.time()
    now = now or time.time()
    if gaps is None:
        gaps = [n for n, _ in current_gaps()]
    since = datetime.datetime.fromtimestamp(st.get("since") or time.time(), tz()).strftime("%H:%M")
    reset = st.get("reset") or "unknown (I will tell you when I know)"
    return (f"{captain_prefix_text()} I'm emergency captain because {(st.get('reason') or 'Claude is out').split(',')[0]}, since {since}, Claude back expected {reset}. "
            f"I handle: {priority_now(now, briefing_hm)}. Waits for {C()['primary_name']}: {'; '.join(gaps) or 'nothing listed'}. Same rules: drafts only, no orders/payments/deletions without your yes.")
# A gap disappears when the check that proves it works passed in the LATEST selftest; retired tools are never listed; any other failing check is a gap right now.
SELFTEST_JSON = f"{STORE}/captain-selftest.json"
def current_gaps(results=None):
    if results is None:
        try: results = json.load(open(SELFTEST_JSON)).get("results") or {}
        except Exception: results = {}
    resolved_by = C()["resolved_by"]; retired = tuple(C()["retired"])
    out = []
    for n, w in C()["gaps"]:
        if retired and any(n.startswith(r) for r in retired): continue
        if any(n.startswith(k) and (results.get(chk) or {}).get("ok") for k, chk in resolved_by.items()): continue
        out.append((n, w))
    mapped = set(resolved_by.values())
    out += [(f"{name} (selftest failing now)", (r.get("detail") or "")[:120]) for name, r in results.items() if not r.get("ok") and name not in mapped]
    return out
def _prefix_re(): return re.compile(r"^\s*(?::rotating_light:\s*)?Emergency captain \(" + re.escape(C()["captain_name"]) + r"\):?\s*", re.I)
def captain_prefix(agent, msg, state):
    """Code, not a rule: during an outage every message the captain sends carries the captain prefix exactly once; with the state 'ok' any hand-typed prefix is removed (it is not the captain then). Anyone else, or an unreadable state (None), leaves the text untouched."""
    if agent != CAP() or state not in ("outage", "ok"): return msg
    stripped = msg; rx = _prefix_re()
    while rx.match(stripped): stripped = rx.sub("", stripped, count=1)      # any number of hand-typed copies, with or without the siren
    return stripped if state == "ok" else captain_prefix_text() + " " + stripped
