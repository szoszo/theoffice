@contextlib.contextmanager
def state_lock(path=None, blocking=True):
    """One writer at a time for outage.json: the detector tick and the captain's switch/unswitch commands each do load-modify-save."""
    f = open((path or STATE) + ".lock", "a")
    try:
        fcntl.flock(f, fcntl.LOCK_EX | (0 if blocking else fcntl.LOCK_NB)); yield
    finally:
        try: fcntl.flock(f, fcntl.LOCK_UN)
        finally: f.close()
def new_state(): return {"state": "ok", "since": 0, "reason": "", "last_probe": 0, "bad_streak": 0, "good_streak": 0}
