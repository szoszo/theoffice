def merge_block(text, block):
    if BEGIN in text and END in text: return re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", lambda m: block, text, flags=re.S)
    return text.rstrip("\n") + "\n\n" + block

def merge_mcp(text, servers):
    """Local stdio MCPs for Codex, present only while the outage lasts (each one is a process). servers=None removes the block."""
    cleaned = re.sub(r"\n?" + re.escape(MCP_BEGIN) + r".*?" + re.escape(MCP_END) + r"\n?", "", text, flags=re.S)
    if not servers: return cleaned
    body = "".join(f'[mcp_servers.{n}]\ncommand = "{c}"\nargs = [{", ".join(json.dumps(a) for a in args)}]\n\n' for n, (c, args) in servers.items())
    return cleaned.rstrip("\n") + "\n\n" + MCP_BEGIN + "\n" + body.rstrip("\n") + "\n" + MCP_END + "\n"
def set_codex_mcp(on):
    path = cfg.path("codex_config"); servers = {n: tuple(v) for n, v in C()["local_mcps"].items()}
    if not servers: return
    cur = open(path).read(); new = merge_mcp(cur, servers if on else None)
    if new != cur: open(path, "w").write(new)

