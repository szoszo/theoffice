def _agent_json(agents_dir, a): return f"{agents_dir}/{a}/agent.json"
def active_switches(st): return [x for x in (st.get("switches") or []) if not x.get("back_at")]
def can_switch(agent, st, agents_dir=None):
    """The captain may move ONE more agent's runtime to Codex, only during an outage: never itself or the primary agent, never one already on Codex, at most max_switched at once (one Plus account)."""
    agents_dir = agents_dir or AGENTS_DIR; mx = C()["max_switched"]
    if st.get("state") != "outage" and not os.environ.get("CAPTAIN_ALLOW_SWITCH_WITHOUT_OUTAGE"): return False, "only during an outage"
    if agent in C()["never_switch"]: return False, f"{agent} is never switched"
    try: cur = json.load(open(_agent_json(agents_dir, agent)))
    except Exception: return False, f"unknown agent {agent}"
    if cur.get("runtime") == "codex": return False, f"{agent} is already on codex"
    if any(x["agent"] == agent for x in active_switches(st)): return False, f"{agent} is already switched"
    if len(active_switches(st)) >= mx: return False, f"max {mx} agents on Codex at once (one Plus account)"
    return True, ""
def apply_switch(st, agent, reason, now, agents_dir=None):
    agents_dir = agents_dir or AGENTS_DIR
    ok, why = can_switch(agent, st, agents_dir)
    if not ok: raise ValueError(why)
    path = _agent_json(agents_dir, agent); cur = json.load(open(path)); before = cur.get("runtime")
    cur["runtime"] = "codex"; json.dump(cur, open(path, "w"), indent=2)
    st = dict(st); st["switches"] = list(st.get("switches") or []) + [{"agent": agent, "reason": reason, "at": now, "runtime_before": before}]
    return st
def revert_all(st, now, agents_dir=None):
    """Every agent the captain switched goes back to exactly its previous runtime (a missing key is removed, not set)."""
    agents_dir = agents_dir or AGENTS_DIR; st = dict(st); back = []; out = []
    for x in st.get("switches") or []:
        if not x.get("back_at"):
            path = _agent_json(agents_dir, x["agent"])
            try:
                cur = json.load(open(path))
                if x.get("runtime_before") is None: cur.pop("runtime", None)
                else: cur["runtime"] = x["runtime_before"]
                json.dump(cur, open(path, "w"), indent=2); back.append(x["agent"]); x = dict(x, back_at=now)
            except Exception as e: print("revert failed for", x["agent"], e, file=sys.stderr)
        out.append(x)
    st["switches"] = out; return st, back
def revert_one(st, agent, now, agents_dir=None):
    """Return ONE switched agent to its previous runtime early; the other switches stay. (st, True) when it was switched, else (st, False)."""
    agents_dir = agents_dir or AGENTS_DIR; st = dict(st); hit = False; out = []
    for x in st.get("switches") or []:
        if x["agent"] == agent and not x.get("back_at"):
            path = _agent_json(agents_dir, agent); cur = json.load(open(path))
            if x.get("runtime_before") is None: cur.pop("runtime", None)
            else: cur["runtime"] = x["runtime_before"]
            json.dump(cur, open(path, "w"), indent=2); x = dict(x, back_at=now); hit = True
        out.append(x)
    st["switches"] = out; return st, hit
