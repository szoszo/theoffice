#!/usr/bin/env python3
"""Sync the Claude skills dir into the Codex skills dir for the captain agent (no AI). Same SKILL.md format (name + description frontmatter). Skills that mention Claude-only
tools get a short human note naming the captain's route; clean skills are copied verbatim. Hash-based, idempotent, prunes skills removed from the source.
Routes = a small generic default list + cfg skill_routes ([pattern, label_or_null, route_text])."""
import hashlib, json, os, re, shutil, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__))); import cfg

MANIFEST = ".captain-synced.json"
def default_routes():  # (pattern, label, the captain's route)
    return [
        (r"\bSkill tool\b|Skill\(", "Skill tool", "No Skill tool: read the other skill's SKILL.md under ~/.codex/skills/<name>/ and follow it."),
        (r"AskUserQuestion|EnterPlanMode|plan mode", None, "No menus or plan mode: ask the owner a plain question in the chat channel and wait."),
        (r"\bAgent tool\b|subagent_type|\bTask tool\b", None, "No sub-agents: do the work inline."),
        (r"ToolSearch|CronCreate|ScheduleWakeup", None, f"Not available: use the fleet services at {cfg.get()['dashboard']} (schedules, kanban)."),
    ]
def routes():
    extra = [(r[0], r[1], r[2]) for r in cfg.get().get("skill_routes") or []]
    return default_routes() + extra
def flags(text):
    hits = []
    for pat, label, _ in routes():
        for m in re.finditer(pat, text): hits.append((m.start(), label or m.group(0)))
    out = []
    for _, name in sorted(hits):
        if name not in out: out.append(name)
    return out
def note(found):
    rs = [r for pat, _, r in routes() if any(re.search(pat, f) for f in found)]
    return "> Codex note (auto-generated by tools/captain/skills_sync.py; the original is untouched): this skill mentions Claude-only tools. " + " ".join(dict.fromkeys(rs)) + "\n\n"
def _body(text):
    f = flags(text)
    if not f: return text, []
    m = re.match(r"(---\n.*?\n---\n)(.*)", text, re.S)
    head, rest = (m.group(1), m.group(2)) if m else ("", text)
    return head + "\n" + note(f) + rest, f
def _digest(path):
    h = hashlib.sha1()
    for dp, dn, fn in sorted(os.walk(path)):
        dn.sort()
        for f in sorted(fn): h.update(f.encode()); h.update(open(os.path.join(dp, f), "rb").read())
    return h.hexdigest()
def sync(src=None, dst=None):
    src = src or cfg.path("skills_src"); dst = dst or cfg.path("skills_dst")
    os.makedirs(dst, exist_ok=True); mf = os.path.join(dst, MANIFEST)
    prev = json.load(open(mf)) if os.path.exists(mf) else {}; cur = {}; copied = 0; flagged = []
    rh = hashlib.sha1(json.dumps(routes()).encode()).hexdigest(); stale_notes = prev.pop("__routes__", None) != rh   # a changed route text (default or configured) must refresh every note
    old = dict(prev)
    if stale_notes: prev = {}
    for n in sorted(os.listdir(src)):
        sp = os.path.join(src, n)
        if n.startswith(".") or not os.path.isfile(os.path.join(sp, "SKILL.md")): continue
        d = _digest(sp); cur[n] = d
        text = open(os.path.join(sp, "SKILL.md")).read(); _, f = _body(text)
        if f: flagged.append(n)
        if prev.get(n) == d and os.path.isdir(os.path.join(dst, n)): continue
        tp = os.path.join(dst, n)
        if os.path.isdir(tp): shutil.rmtree(tp)
        shutil.copytree(sp, tp, symlinks=True)
        if f: open(os.path.join(tp, "SKILL.md"), "w").write(_body(text)[0])
        copied += 1
    removed = [n for n in old if n not in cur]
    for n in removed: shutil.rmtree(os.path.join(dst, n), ignore_errors=True)
    json.dump(dict(cur, __routes__=rh), open(mf, "w"))
    return {"copied": copied, "flagged": flagged, "removed": removed, "total": len(cur)}
if __name__ == "__main__":
    r = sync(); print(f"skills synced: {r['copied']} copied, {r['total']} total, {len(r['flagged'])} with a Codex note, {len(r['removed'])} removed")
